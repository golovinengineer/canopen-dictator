mod common;

use dictator_canfestival::{gen_c, od};
use dictator_core::project;

/// The reference files were run through clang-format, so only the token
/// stream is comparable: drop all whitespace.
fn squash(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}

fn assert_same(ours: &str, theirs: &str, what: &str) {
    let (a, b) = (squash(ours), squash(theirs));
    if a == b {
        return;
    }
    let (a, b): (Vec<char>, Vec<char>) = (a.chars().collect(), b.chars().collect());
    let at = a.iter().zip(&b).position(|(x, y)| x != y).unwrap_or(a.len().min(b.len()));
    let ctx = |v: &[char]| -> String {
        v[at.saturating_sub(120)..(at + 120).min(v.len())].iter().collect()
    };
    panic!("{what} differs at squashed offset {at}\n ours:   {}\n theirs: {}", ctx(&a), ctx(&b));
}

/// `ObjDict.c/.h` were generated by CanFestival from `ObjDict.od`, so the
/// import must lead back to the same C code.
#[test]
fn imported_od_generates_the_reference_c() {
    let import = od::load(&common::asset("ObjDict.od")).unwrap();
    assert!(import.warnings.is_empty(), "{:?}", import.warnings);
    let (c, h) = gen_c::generate(&import.od, "ObjDict.h").unwrap();
    assert_same(&h, &common::read_asset("ObjDict.h"), "ObjDict.h");
    assert_same(&c, &common::read_asset("ObjDict.c"), "ObjDict.c");
}

/// The import survives being saved as a project file and loaded again.
#[test]
fn imported_od_round_trips_through_the_project_file() {
    let od = od::load(&common::asset("ObjDict.od")).unwrap().od;
    let again = project::from_toml(&project::to_toml(&od)).unwrap();
    assert_eq!(again, od);
}
